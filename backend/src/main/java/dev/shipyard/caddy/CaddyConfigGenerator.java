package dev.shipyard.caddy;

import java.util.List;
import java.util.stream.Collectors;

/** Renders a Caddyfile from platform routes. Pure function; unit tested. */
public final class CaddyConfigGenerator {
    private CaddyConfigGenerator() {}

    public static String generate(String adminDirective, String acmeEmail, String platformDomain, String platformUpstream,
                                  List<CaddyRoute> routes) {
        StringBuilder f = new StringBuilder();
        f.append("# Generated by Shipyard. Do not edit: changes are overwritten on every deployment.\n");
        f.append("{\n");
        if (adminDirective != null && !adminDirective.isBlank()) f.append("\tadmin ").append(adminDirective).append('\n');
        if (acmeEmail != null && !acmeEmail.isBlank()) f.append("\temail ").append(acmeEmail.strip()).append('\n');
        f.append("}\n\n");
        f.append("(shipyard_common) {\n\tencode zstd gzip\n\theader -Server\n}\n\n");

        if (platformDomain != null && !platformDomain.isBlank()) {
            f.append(platformDomain.strip()).append(" {\n\timport shipyard_common\n\treverse_proxy ")
                    .append(platformUpstream).append(" {\n\t\tflush_interval -1\n\t}\n}\n\n");
        }

        for (CaddyRoute r : routes) {
            if (r.hosts().isEmpty()) continue;
            String addresses = r.hosts().stream()
                    .map(h -> h.tls() ? h.hostname() : "http://" + h.hostname())
                    .collect(Collectors.joining(", "));
            f.append("# application: ").append(r.applicationSlug()).append('\n');
            f.append(addresses).append(" {\n\timport shipyard_common\n");
            if (r.staticRoot() != null) {
                f.append("\troot * ").append(quote(r.staticRoot())).append('\n');
                f.append("\ttry_files {path} {path}/ /index.html\n");
                f.append("\tfile_server\n");
            } else if (r.upstream() != null) {
                f.append("\treverse_proxy ").append(r.upstream()).append('\n');
            } else {
                f.append("\trespond ").append(quote(r.unavailableMessage() == null ? "Application unavailable" : r.unavailableMessage()))
                        .append(" 503\n");
            }
            f.append("}\n\n");
        }
        return f.toString();
    }

    private static String quote(String s) {
        if (s.matches("[A-Za-z0-9/._-]+")) return s;
        return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }
}
