package dev.shipyard.caddy;

import java.util.List;
import java.util.stream.Collectors;

/** Renders a Caddyfile from platform routes. Pure function; unit tested. */
public final class CaddyConfigGenerator {
    private CaddyConfigGenerator() {}

    /** Response types Caddy compresses (its defaults, minus text/event-stream). */
    static final String COMPRESSIBLE_TYPES = String.join(" ",
            "text/html*", "text/css*", "text/plain*", "text/javascript*", "text/xml*", "text/csv*", "text/markdown*",
            "application/json*", "application/javascript*", "application/x-javascript*", "application/xml*",
            "application/xhtml+xml*", "application/rss+xml*", "application/atom+xml*", "application/ld+json*",
            "application/manifest+json*", "application/geo+json*", "application/wasm*",
            "image/svg+xml*", "image/x-icon*", "image/vnd.microsoft.icon*", "font/*");

    private static final String MAINTENANCE_MESSAGE =
            "This application is currently being updated, please try again in a few minutes.";
    private static final String MAINTENANCE_PAGE = "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
            + "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\"><meta name=\"robots\" content=\"noindex\">"
            + "<title>Application update in progress</title></head>"
            + "<body style=\"box-sizing:border-box;min-height:100vh;margin:0;display:grid;place-items:center;padding:24px;"
            + "background:#f5f7fa;color:#182230;font:16px/1.6 system-ui,-apple-system,BlinkMacSystemFont,sans-serif\">"
            + "<main style=\"box-sizing:border-box;width:100%;max-width:480px;padding:42px 28px;text-align:center;"
            + "background:#fff;border:1px solid #e5eaf0;border-radius:24px;box-shadow:0 16px 48px rgba(16,24,40,.08)\">"
            + "<div style=\"display:grid;place-items:center;width:56px;height:56px;margin:0 auto 24px;border-radius:50%;"
            + "background:#eff6ff;color:#2563eb;font-size:28px\" aria-hidden=\"true\">&#8635;</div>"
            + "<h1 style=\"margin:0 0 12px;font-size:24px;line-height:1.25\">We'll be back shortly</h1>"
            + "<p style=\"margin:0;color:#596579\">" + MAINTENANCE_MESSAGE + "</p></main></body></html>";

    public static String generate(String adminDirective, boolean https, String acmeEmail, String platformDomain, String platformUpstream,
                                  List<CaddyRoute> routes) {
        StringBuilder f = new StringBuilder();
        f.append("# Generated by Shipyard. Do not edit: changes are overwritten on every deployment.\n");
        f.append("{\n");
        if (adminDirective != null && !adminDirective.isBlank()) f.append("\tadmin ").append(adminDirective).append('\n');
        if (https && acmeEmail != null && !acmeEmail.isBlank()) f.append("\temail ").append(acmeEmail.strip()).append('\n');
        // Without HTTPS Caddy must never obtain certificates or open 443: it only
        // serves the plain-HTTP listeners configured below.
        if (!https) f.append("\tauto_https off\n");
        f.append("}\n\n");
        // Compress the usual text types but never text/event-stream: compressing
        // Server-Sent Events buffers them, so live build logs and status
        // updates would arrive late or in bursts.
        f.append("(shipyard_common) {\n\tencode zstd gzip {\n\t\tmatch {\n\t\t\theader Content-Type ")
                .append(COMPRESSIBLE_TYPES).append("\n\t\t}\n\t}\n\theader -Server\n}\n\n");

        if (platformDomain != null && !platformDomain.isBlank()) {
            f.append(address(platformDomain.strip(), https)).append(" {\n\timport shipyard_common\n\treverse_proxy ")
                    .append(platformUpstream).append(" {\n\t\tflush_interval -1\n\t}\n}\n\n");
        } else if (platformUpstream != null && !platformUpstream.isBlank()) {
            f.append(":80 {\n\timport shipyard_common\n\treverse_proxy ")
                    .append(platformUpstream).append(" {\n\t\tflush_interval -1\n\t}\n}\n\n");
        }

        for (CaddyRoute r : routes) {
            if (r.hosts().isEmpty()) continue;
            String addresses = r.hosts().stream()
                    .map(h -> address(h.hostname(), https && h.tls()))
                    .collect(Collectors.joining(", "));
            f.append("# application: ").append(r.applicationSlug()).append('\n');
            f.append(addresses).append(" {\n\timport shipyard_common\n");
            if (r.maintenance()) {
                f.append("\theader Content-Type \"text/html; charset=utf-8\"\n");
                f.append("\theader Cache-Control \"no-store\"\n");
                f.append("\trespond ").append(quote(MAINTENANCE_PAGE)).append(" 503\n");
            } else if (r.staticRoot() != null) {
                f.append("\troot * ").append(quote(r.staticRoot())).append('\n');
                f.append("\ttry_files {path} {path}/ /index.html\n");
                f.append("\tfile_server\n");
            } else if (r.upstream() != null) {
                f.append("\treverse_proxy ").append(r.upstream()).append('\n');
            } else {
                f.append("\trespond ").append(quote(r.unavailableMessage() == null ? "Application unavailable" : r.unavailableMessage()))
                        .append(" 503\n");
            }
            f.append("}\n\n");
        }
        return f.toString();
    }

    /** A site address: a bare host turns on automatic HTTPS, {@code http://host} serves cleartext only. */
    private static String address(String hostname, boolean tls) {
        return tls ? hostname : "http://" + hostname;
    }

    private static String quote(String s) {
        if (s.matches("[A-Za-z0-9/._-]+")) return s;
        return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }
}
