package dev.shipyard.builds;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.ObjectMapper;
import dev.shipyard.detection.BuildStrategy;
import dev.shipyard.detection.DetectionResult;
import java.util.Collection;
import java.util.List;

/**
 * Generates Dockerfiles for projects without one. Every build step runs
 * inside a container; static sites use a final {@code export} stage that
 * contains only the build output, exported with {@code --output type=local}.
 */
public final class DockerfileGenerator {
    public static final String EXPORT_STAGE = "export";
    private static final ObjectMapper JSON = new ObjectMapper();

    private DockerfileGenerator() {}

    public static String generate(DetectionResult d, Collection<String> buildArgNames) {
        BuildStrategy s = d.buildStrategy();
        StringBuilder f = new StringBuilder("# Generated by Shipyard for strategy ").append(s).append('\n');
        switch (s) {
            case NODE_STATIC -> {
                f.append("FROM ").append(image(d, "node:lts-alpine")).append(" AS build\n");
                f.append("WORKDIR /src\nCOPY . .\n");
                args(f, buildArgNames);
                run(f, d.installCommand());
                run(f, d.buildCommand());
                run(f, d.testCommand());
                f.append("FROM scratch AS ").append(EXPORT_STAGE).append('\n');
                f.append("COPY --from=build /src/").append(trimSlashes(d.outputDirectory() == null ? "dist" : d.outputDirectory())).append("/ /\n");
            }
            case NODE_SERVER, BUN_SERVER -> {
                f.append("FROM ").append(image(d, s == BuildStrategy.BUN_SERVER ? "oven/bun:1" : "node:lts-alpine")).append('\n');
                f.append("WORKDIR /app\nCOPY . .\n");
                args(f, buildArgNames);
                run(f, d.installCommand());
                run(f, d.buildCommand());
                run(f, d.testCommand());
                f.append("ENV NODE_ENV=production\n");
                port(f, d);
                cmd(f, d.startCommand() == null ? "npm start" : d.startCommand());
            }
            case PYTHON -> {
                f.append("FROM ").append(image(d, "python:3.12-slim")).append('\n');
                f.append("ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1\nWORKDIR /app\nCOPY . .\n");
                args(f, buildArgNames);
                run(f, d.installCommand());
                run(f, d.buildCommand());
                run(f, d.testCommand());
                port(f, d);
                cmd(f, d.startCommand());
            }
            case GO -> {
                f.append("FROM golang:1 AS build\nWORKDIR /src\nCOPY . .\n");
                args(f, buildArgNames);
                f.append("RUN go mod download\n");
                run(f, d.testCommand());
                run(f, d.buildCommand() == null ? "CGO_ENABLED=0 go build -o /out/server ." : d.buildCommand());
                f.append("FROM ").append(image(d, "alpine:3")).append("\nWORKDIR /app\nCOPY --from=build /out/ /app/\n");
                port(f, d);
                cmd(f, d.startCommand() == null ? "/app/server" : d.startCommand());
            }
            case RUST -> {
                f.append("FROM rust:1 AS build\nWORKDIR /src\nCOPY . .\n");
                args(f, buildArgNames);
                run(f, d.testCommand());
                run(f, d.buildCommand() == null ? "cargo build --release" : d.buildCommand());
                f.append("RUN mkdir -p /out && find target/release -maxdepth 1 -type f -perm -u+x -exec cp {} /out/ \\;\n");
                f.append("FROM ").append(image(d, "debian:bookworm-slim"))
                        .append("\nRUN apt-get update && apt-get install -y --no-install-recommends ca-certificates && rm -rf /var/lib/apt/lists/*\n")
                        .append("WORKDIR /app\nCOPY --from=build /out/ /app/\n");
                port(f, d);
                cmd(f, d.startCommand());
            }
            case MAVEN -> {
                f.append("FROM maven:3-eclipse-temurin-21 AS build\nWORKDIR /src\nCOPY . .\n");
                args(f, buildArgNames);
                run(f, d.testCommand());
                run(f, d.buildCommand() == null ? "mvn -B -DskipTests package" : d.buildCommand());
                f.append("RUN cp \"$(find target -maxdepth 1 -name '*.jar' ! -name '*-sources.jar' ! -name '*-javadoc.jar' ! -name 'original-*' | head -n1)\" /app.jar\n");
                javaRuntime(f, d);
            }
            case GRADLE -> {
                f.append("FROM gradle:jdk21 AS build\nWORKDIR /src\nCOPY . .\n");
                args(f, buildArgNames);
                run(f, d.testCommand());
                run(f, d.buildCommand() == null ? "gradle --no-daemon build -x test" : d.buildCommand());
                f.append("RUN cp \"$(find build/libs -name '*.jar' ! -name '*-plain.jar' | head -n1)\" /app.jar\n");
                javaRuntime(f, d);
            }
            case DOTNET -> {
                f.append("FROM mcr.microsoft.com/dotnet/sdk:8.0 AS build\nWORKDIR /src\nCOPY . .\n");
                args(f, buildArgNames);
                run(f, d.testCommand());
                run(f, d.buildCommand() == null ? "dotnet publish -c Release -o /out" : d.buildCommand());
                f.append("FROM ").append(image(d, "mcr.microsoft.com/dotnet/aspnet:8.0")).append("\nWORKDIR /app\nCOPY --from=build /out/ /app/\n");
                f.append("ENV ASPNETCORE_HTTP_PORTS=").append(d.port() == null ? 8080 : d.port()).append('\n');
                port(f, d);
                cmd(f, d.startCommand());
            }
            case PHP -> {
                if (d.installCommand() != null) {
                    f.append("FROM composer:2 AS deps\nWORKDIR /app\nCOPY . .\n");
                    run(f, d.installCommand() + " --ignore-platform-reqs");
                    f.append("FROM ").append(image(d, "php:8.3-apache")).append("\nCOPY --from=deps /app/ /var/www/html/\n");
                } else {
                    f.append("FROM ").append(image(d, "php:8.3-apache")).append("\nCOPY . /var/www/html/\n");
                }
                run(f, d.testCommand());
                port(f, d);
            }
            default -> throw new IllegalArgumentException("No Dockerfile template for " + s);
        }
        return f.toString();
    }

    private static void javaRuntime(StringBuilder f, DetectionResult d) {
        f.append("FROM ").append(image(d, "eclipse-temurin:21-jre")).append("\nWORKDIR /app\nCOPY --from=build /app.jar /app/app.jar\n");
        port(f, d);
        cmd(f, d.startCommand() == null ? "java -jar /app/app.jar" : d.startCommand());
    }

    private static String image(DetectionResult d, String fallback) {
        String r = d.runtime();
        return r == null || r.isBlank() || r.equals("Dockerfile") ? fallback : r;
    }

    private static void args(StringBuilder f, Collection<String> names) {
        for (String n : names) f.append("ARG ").append(n).append('\n');
    }

    private static void run(StringBuilder f, String command) {
        if (command == null || command.isBlank()) return;
        // Use the shell form so commands like "corepack enable && pnpm install" work.
        f.append("RUN ").append(command.replace("\n", " ")).append('\n');
    }

    private static void port(StringBuilder f, DetectionResult d) {
        int p = d.port() == null ? 8080 : d.port();
        f.append("ENV PORT=").append(p).append("\nEXPOSE ").append(p).append('\n');
    }

    private static void cmd(StringBuilder f, String start) {
        if (start == null || start.isBlank()) throw new IllegalArgumentException("A start command is required for server applications");
        try {
            f.append("CMD ").append(JSON.writeValueAsString(List.of("sh", "-c", start))).append('\n');
        } catch (JsonProcessingException e) {
            throw new IllegalStateException(e);
        }
    }

    private static String trimSlashes(String s) {
        String t = s.replaceAll("^\\./", "").replaceAll("^/+|/+$", "");
        return t.isEmpty() || t.equals(".") ? "" : t;
    }
}
